#pragma once
#include <windows.h>
/* Input decision is shared by the main HWND and panel pretranslation.
   Suppression follows the scan code, so a character from another layout/key
   is not mistaken for the character generated by an earlier OEM_3 press. */
struct CatherineDevTildeInput {
 enum Decision { Pass, Consume, Toggle };
 bool suppress_oem_character=false;
 unsigned oem_scan=0;
 Decision event(UINT message,WPARAM key,LPARAM flags) {
  const bool down=message==WM_KEYDOWN||message==WM_SYSKEYDOWN;
  const bool up=message==WM_KEYUP||message==WM_SYSKEYUP;
  const bool repeated=(flags&(LPARAM(1)<<30))!=0;
  const unsigned scan=unsigned((uintptr_t(flags)>>16)&0xffu);
  if(down){
   if(key==VK_OEM_3){
    if(repeated)return Consume;
    suppress_oem_character=true;oem_scan=scan;return Toggle;
   }
   // A different physical key cannot belong to the earlier OEM character.
   suppress_oem_character=false;
  }
  if(up&&key==VK_OEM_3){suppress_oem_character=false;return Consume;}
  if(message==WM_CHAR||message==WM_SYSCHAR){
   const bool oem_char=(key=='~'||key=='`')&&suppress_oem_character&&scan==oem_scan;
   if(oem_char){suppress_oem_character=false;return Consume;}
   if(key=='~')return repeated?Consume:Toggle;
  }
  return Pass;
 }
};
