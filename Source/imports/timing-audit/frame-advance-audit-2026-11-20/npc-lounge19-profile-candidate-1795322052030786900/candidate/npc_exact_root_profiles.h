constexpr bool descriptor_consistent(const Profile& p) noexcept {
 if(!p.nodes || p.root_dfs!=0 || p.root_name!="RootNode" || p.weighted+p.rigid!=p.meshes ||
    p.rigid_members.size()!=p.rigid || p.warm_copies!=p.rigid*3 || p.palette_node_dfs.empty() || p.expected_gfs_sha256.size()!=64) return false;
 for(auto n:p.palette_node_dfs) if(n>=p.nodes || n==p.root_dfs) return false;
 for(size_t i=0;i<p.rigid_members.size();++i) {
  const auto& m=p.rigid_members[i];
  if(m.ordinal>=p.meshes || m.node_dfs>=p.nodes || (m.authored_flags&1u) || (m.authored_flags&32u))return false;
  for(size_t j=0;j<i;++j)if(p.rigid_members[j].ordinal==m.ordinal)return false;
 }
 return true;
}
constexpr const Profile* lookup(uint32_t kind,uint32_t variant,uint32_t resource,std::string_view copied_actual_path) noexcept {
 for(const auto& p:profiles)if(p.kind==kind&&p.variant==variant&&p.resource==resource&&p.actual_gfs_path==copied_actual_path)return &p;
 return nullptr;
}
// Optional offline/resource-loader digest check. No hashing or guest reads occur here.
constexpr const Profile* lookup_verified(uint32_t kind,uint32_t variant,uint32_t resource,std::string_view copied_actual_path,std::string_view observed_gfs_sha256) noexcept {
 const auto* p=lookup(kind,variant,resource,copied_actual_path);
 return p && p->expected_gfs_sha256==observed_gfs_sha256 ? p : nullptr;
}
