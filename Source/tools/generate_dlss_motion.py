"""Compile and validate the dense-motion shader used by DLSS Frame Generation."""
from pathlib import Path
import hashlib,struct,subprocess,tempfile
root=Path(__file__).resolve().parents[1]/'imports/graphics/src/nvn'
source=root/'shaders/dlss_motion.comp'
with tempfile.TemporaryDirectory(prefix='catherine-motion-') as temporary:
 binary=Path(temporary)/'motion.spv'
 subprocess.run(['glslc','-O','--target-env=vulkan1.1',str(source),'-o',str(binary)],check=True)
 subprocess.run(['spirv-val','--target-env','vulkan1.1',str(binary)],check=True)
 raw=binary.read_bytes()
words=struct.unpack('<'+'I'*(len(raw)//4),raw)
text='// Generated by Source/tools/generate_dlss_motion.py; do not edit.\n'
text+='// GLSL SHA256: '+hashlib.sha256(source.read_bytes()).hexdigest()+'\nconst uint32_t kMotionShader[]={\n'
for i in range(0,len(words),8):text+=' '+','.join(f'0x{x:08x}'for x in words[i:i+8])+',\n'
text+='};\n'
(root/'dlss_motion_shader.inc').write_text(text,encoding='utf-8',newline='\n')
print('Validated motion shader:',len(raw),'bytes')
