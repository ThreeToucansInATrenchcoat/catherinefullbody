"""Regenerate the embedded NVN present fragment shader; no runtime compiler needed."""
import argparse
import hashlib
from pathlib import Path
import struct
import subprocess
import tempfile

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--glslc', default='glslc')
parser.add_argument('--spirv-val', default='spirv-val')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
source = root / 'src/nvn/shaders/present.frag'
output = root / 'src/nvn/nvn_present_fragment.inc'
with tempfile.TemporaryDirectory(prefix='catherine-present-') as temporary:
    binary = Path(temporary) / 'present.spv'
    subprocess.run([args.glslc, '-O', '--target-env=vulkan1.0', '-fshader-stage=frag',
                    str(source), '-o', str(binary)], check=True)
    subprocess.run([args.spirv_val, '--target-env', 'vulkan1.0', str(binary)], check=True)
    raw = binary.read_bytes()
words = struct.unpack('<' + 'I' * (len(raw) // 4), raw)
result = '// Generated by tools/generate-present-shader.py; do not edit.\n'
result += '// GLSL SHA256: ' + hashlib.sha256(source.read_bytes()).hexdigest() + '\n'
result += 'const uint32_t kFragment[] = {\n'
for index in range(0, len(words), 8):
    result += '    ' + ', '.join(f'0x{word:08x}' for word in words[index:index+8]) + ',\n'
result += '};\n'
if args.check:
    if output.read_text() != result:
        raise SystemExit('Embedded present shader is stale; regenerate it.')
else:
    output.write_text(result, encoding='utf-8', newline='\n')
print(f'Validated present shader: {len(raw)} bytes; embedded source ' + ('matches' if args.check else 'updated'))
